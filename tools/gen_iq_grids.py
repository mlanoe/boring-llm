#!/usr/bin/env python3
"""Generates src/iq_grids.br: the lookup grids of the IQ1/IQ2/IQ3 quantization formats
(ggml's iq2xxs_grid, iq2xs_grid, iq2s_grid, iq3xxs_grid, iq3s_grid, iq1s_grid and
ksigns_iq2xs), taken from the Python `gguf` package, which carries them compressed.

    .venv/bin/python tools/gen_iq_grids.py

Each table is a hex string of one byte per grid value (IQ1's values -1/0/1 are stored
plus one), decoded once at first use by src/iq_grids.br's helpers.
"""
from gguf import quants as Q

TABLES = [  # (constant name, gguf class, bias)
    ("IQ2XXS", Q.IQ2_XXS, 0),
    ("IQ2XS", Q.IQ2_XS, 0),
    ("IQ2S", Q.IQ2_S, 0),
    ("IQ3XXS", Q.IQ3_XXS, 0),
    ("IQ3S", Q.IQ3_S, 0),
    ("IQ1S", Q.IQ1_S, 1),
]

out = [
    "# GENERATED by tools/gen_iq_grids.py from the Python `gguf` package: do not edit.",
    "# Lookup grids of the IQ1/IQ2/IQ3 formats as hex strings, one byte per grid value",
    "# (the IQ1 grid holds -1/0/1 stored plus one).",
    "",
]
for name, cls, bias in TABLES:
    cls.init_grid()
    flat = cls.grid.reshape(-1)
    data = bytes(int(v) + bias for v in flat)
    assert all(int(v) + bias == b for v, b in zip(flat, data))
    out.append(f"# {name}: {cls.grid.shape[-2]} entries of {cls.grid.shape[-1]} values")
    out.append(f'pub let string {name}_GRID_HEX = "{data.hex()}"')
    out.append("")
signs = bytes(Q.IQ2_XXS.ksigns)
assert len(signs) == 128
out.append("# ksigns_iq2xs: the 128 sign patterns (7 stored bits plus a parity bit)")
out.append(f'pub let string KSIGNS_HEX = "{signs.hex()}"')
out.append("")
open("src/iq_grids.br", "w").write("\n".join(out))
print("wrote src/iq_grids.br,", sum(len(t) for t in out), "chars")
